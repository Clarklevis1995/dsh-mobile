package com.clarklevis.dsh.android.localization

import java.util.Locale

/**
 * App-authored text shared by Compose, presenters, and platform callbacks.
 *
 * Chinese source keys mirror the iOS catalog. Only fixed app copy goes through this
 * catalog; conversation content, paths, and gateway-provided names stay unchanged.
 * Resolve on access so enum labels and retained presenters follow the active locale.
 */
internal fun appText(source: String, vararg arguments: Any?): String =
    AndroidStrings.text(source, Locale.getDefault(), *arguments)

internal object AndroidStrings {
    private val placeholder = Regex("%(\\d+)\\\$s")

    fun text(source: String, locale: Locale, vararg arguments: Any?): String {
        val template = when {
            locale.language == "zh" -> source
            arguments.firstOrNull()?.toString() == "1" -> singularEnglish[source] ?: english[source] ?: source
            else -> english[source] ?: source
        }
        if (arguments.isEmpty()) return template
        // Replace indexed arguments directly: percent signs and '$' in user values
        // are literals, and translated sentences may reorder or repeat arguments.
        return placeholder.replace(template) { match ->
            arguments[match.groupValues[1].toInt() - 1].toString()
        }
    }

